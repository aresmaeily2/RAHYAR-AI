'use client'

// ─── لایه تجربه محیطی رهیار — قراردادها ─────────────────────────
// AmbientEngine تنها منبع حقیقت «حال محیط» است. هیچ صفحه یا
// کامپوننتی حق ندارد مستقیماً افکت بسازد؛ فقط وضعیت معنایی را
// به Engine اعلام می‌کند و جلوه‌ها از اینجا توزیع می‌شوند.

/** باند زمانی روز — ظاهر و نور برنامه را تدریجی تغییر می‌دهد */
export type AmbientTimeOfDay =
  | 'dawn'      // سپیده — نور گرم صورتی
  | 'morning'   // صبح — نور گرم ملایم
  | 'noon'      // ظهر — نور طبیعی خنثی
  | 'afternoon' // بعدازظهر — گرمای اولیه
  | 'sunset'    // غروب — نور طلایی
  | 'evening'   // شب‌هنگام — نور آبی آرام
  | 'night'     // شب — نور سرد و کم

/** فصل — تینت بسیار ظریف نور و طبیعت */
export type AmbientSeason = 'spring' | 'summer' | 'autumn' | 'winter'

/** حالت هویت زنده دستیار — ۸ حالت با رفتار بصری مخصوص هرکدام */
export type AmbientOrbState =
  | 'idle'      // آماده — تنفس آرام
  | 'breathing' // نفس عمیق — خوش‌آمد/آماده‌باش (کم‌هزینه، عمیق‌تر از idle)
  | 'glow'      // درخشش — جشن موفقیت (گذرا، خودبازگشت)
  | 'pulse'     // تپش هشدار — یادآوری/توجه (گذرا، خودبازگشت)
  | 'listening' // شنیدن — حلقه‌های منتشرشونده
  | 'thinking'  // فکر کردن — حلقه مداری
  | 'streaming' // نوشتن پاسخ — جریان چرخان
  | 'speaking'  // صحبت — تپش با موج صدا

/** حالت‌های گذرا — مدت نمایش و خودبازگشت به حالت قبل (ms) */
export const TRANSIENT_ORB: Partial<Record<AmbientOrbState, number>> = {
  glow: 2400,     // جشن موفقیت — کوتاه و گرم
  pulse: 2400,    // هشدار یادآوری — کوتاه
  breathing: 4200, // خوش‌آمد اولیه — یک نفس عمیق
}

/** عکس لحظه‌ای محیط — فقط خواندنی؛ Engine مالک آن است */
export interface AmbientSnapshot {
  /** باند زمانی روز — هر دقیقه بازمحاسبه می‌شود */
  time: AmbientTimeOfDay
  /** فصل جاری از تقویم میلادی (نیم‌کره شمالی) */
  season: AmbientSeason
  /** حالت تمرکز — محیط تقریباً ساکت می‌شود */
  focus: boolean
  /** سوییچ کاربر برای جلوه‌ها (کلید ara-effects — سازگار با قبل) */
  effects: boolean
  /** احترام به prefers-reduced-motion سیستم */
  reduced: boolean
  /** تب پنهان — همه انیمیشن‌ها متوقف */
  frozen: boolean
  /** حالت فعلی هویت دستیار */
  orb: AmbientOrbState
}
